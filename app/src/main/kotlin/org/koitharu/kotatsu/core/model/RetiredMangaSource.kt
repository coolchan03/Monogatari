package org.koitharu.kotatsu.core.model

import org.koitharu.kotatsu.parsers.model.MangaSource

/**
 * A source id that is stored in the user's data (favourites, history, bookmarks, downloads, backups)
 * but whose parser no longer ships with the bundled parser library.
 *
 * The id is kept verbatim so nothing is deleted or rewritten; [MangaSource] resolves such names to this
 * type instead of [UnknownMangaSource]. It has no repository (the factory falls back to
 * EmptyMangaRepository), so saved titles stay visible and are labelled as retired.
 */
data class RetiredMangaSource(override val name: String) : MangaSource {

	/** Name the source was published under when it still shipped. */
	val formerTitle: String
		get() = RetiredSources.find(name)?.title ?: name

	val isNsfw: Boolean
		get() = RetiredSources.find(name)?.isAdult == true
}

/**
 * A title imported from Mangayomi whose extension was not installed at import time. The importer stores it under
 * "MANGAYOMI_<SOURCE NAME>" (see MangayomiImportPlanner.fallbackSourceName) so it can still be found and moved.
 *
 * Without this type such a name resolved to [UnknownMangaSource], and saving the title again would have replaced the
 * stored name with "UNKNOWN", losing the only record of where it came from. The name is kept verbatim. There is no
 * repository for it (the factory falls back to EmptyMangaRepository), so opening it offers Alternatives as before.
 */
data class MissingExtensionSource(override val name: String) : MangaSource {

	/** "MANGAYOMI_EXAMPLE_SCANS" -> "Example Scans". Only a label; the stored name is [name]. */
	val displayName: String
		get() = name.removePrefix(PREFIX).split('_').filter { it.isNotEmpty() }
			.joinToString(" ") { word -> word.lowercase().replaceFirstChar { it.titlecase() } }

	companion object {

		const val PREFIX = "MANGAYOMI_"

		fun isMissingExtensionName(name: String): Boolean = name.length > PREFIX.length && name.startsWith(PREFIX)
	}
}

